"""Replay the exported OpenRefine operations against the input CSV and compare
the result with the working CSV exported from OpenRefine.

Requires a running local OpenRefine (default http://127.0.0.1:3333).
A temporary project is created and deleted again.

Usage: python scripts/replay_openrefine.py [openrefine_url]
"""

import csv
import io
import json
import sys
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
INPUT_CSV = ROOT / "data/input/bibliographic_metadata_cleaned.csv"
WORKING_CSV = ROOT / "data/intermediate/dublin_core_mapping_working.csv"
OPERATIONS = ROOT / "openrefine/dublin-core-operations.json"
REPORT = ROOT / "reports/openrefine-replay.md"

# Same import settings as Project 01: no type guessing, no whitespace trimming.
IMPORT_OPTIONS = {
    "encoding": "UTF-8",
    "separator": ",",
    "headerLines": 1,
    "ignoreLines": -1,
    "skipDataLines": 0,
    "limit": -1,
    "guessCellValueTypes": False,
    "processQuotes": True,
    "storeBlankRows": True,
    "storeBlankCellsAsNulls": True,
    "includeFileSources": False,
    "trimStrings": False,
}


def csrf(base):
    return requests.get(f"{base}/command/core/get-csrf-token").json()["token"]


def create_project(base):
    response = requests.post(
        f"{base}/command/core/create-project-from-upload",
        params={"csrf_token": csrf(base)},
        data={
            "project-name": "TEMP replay doaj-dublin-core-mapping",
            "format": "text/line-based/*sv",
            "options": json.dumps(IMPORT_OPTIONS),
        },
        files={"project-file": (INPUT_CSV.name, INPUT_CSV.read_bytes(), "text/csv")},
        allow_redirects=False,
    )
    return response.headers["Location"].split("project=")[1]


def apply_operations(base, project_id, operations):
    response = requests.post(
        f"{base}/command/core/apply-operations",
        params={"project": project_id, "csrf_token": csrf(base)},
        data={"operations": json.dumps(operations)},
    )
    return response.json()


def export_csv(base, project_id):
    response = requests.post(
        f"{base}/command/core/export-rows/replay.csv",
        params={"csrf_token": csrf(base)},
        data={
            "project": project_id,
            "format": "csv",
            "engine": json.dumps({"facets": [], "mode": "row-based"}),
        },
    )
    response.encoding = "utf-8"
    return response.text


def delete_project(base, project_id):
    requests.post(
        f"{base}/command/core/delete-project",
        params={"csrf_token": csrf(base)},
        data={"project": project_id},
    )


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:3333"
    version = requests.get(f"{base}/command/core/get-version").json()["full_name"]
    operations = json.loads(OPERATIONS.read_text(encoding="utf-8"))

    project_id = create_project(base)
    try:
        result = apply_operations(base, project_id, operations)
        replayed = export_csv(base, project_id)
    finally:
        delete_project(base, project_id)

    replayed_rows = list(csv.reader(io.StringIO(replayed)))
    working_rows = list(csv.reader(WORKING_CSV.open(encoding="utf-8", newline="")))
    differing = [i for i, (a, b) in enumerate(zip(replayed_rows, working_rows)) if a != b]
    identical = len(replayed_rows) == len(working_rows) and not differing
    byte_identical = replayed.encode("utf-8") == WORKING_CSV.read_bytes()

    lines = [
        "# OpenRefine replay check",
        "",
        "Generated by `scripts/replay_openrefine.py`.",
        "",
        f"- OpenRefine: {version}",
        f"- Input: `{INPUT_CSV.relative_to(ROOT)}`",
        f"- Operations: `{OPERATIONS.relative_to(ROOT)}` ({len(operations)} operations)",
        f"- Operation types: {sorted({op['op'] for op in operations})}",
        f"- New columns: {[op['newColumnName'] for op in operations]}",
        f"- apply-operations response code: `{result.get('code')}`",
        f"- Replayed export: {len(replayed_rows) - 1} records x {len(replayed_rows[0])} columns",
        f"- Working CSV: {len(working_rows) - 1} records x {len(working_rows[0])} columns",
        f"- Header identical: {replayed_rows[0] == working_rows[0]}",
        f"- All parsed rows identical: {identical} (differing rows: {len(differing)})",
        f"- Byte-identical file: {byte_identical}",
        "",
        "RESULT: " + ("PASS" if identical else "FAIL"),
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    sys.exit(0 if identical else 1)


if __name__ == "__main__":
    main()
